import { useState, useRef, useCallback } from "react";
import { TrainingRequestForm } from "@/components/TrainingRequestForm";
import { parseImportedJson } from "@/components/ImportRequestModal";
import { HeartPulse, CheckCircle2, Upload, FileJson, AlertCircle, X } from "lucide-react";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import type { CertificationType } from "@workspace/api-client-react";

interface ParsedRequest {
  locationName?: string;
  address?: string;
  requestorName?: string;
  requestorEmail?: string;
  requestorPhone?: string;
  certificationType?: CertificationType;
  numberOfClasses?: number;
  attendeeCount?: number;
  businessUnit?: string;
  notes?: string;
  sessions?: { date: string; startTime: string }[];
}

function UploadBanner({
  fileName,
  onClear,
}: {
  fileName: string;
  onClear: () => void;
}) {
  return (
    <div className="flex items-center gap-2 rounded-lg border border-green-200 bg-green-50 dark:border-green-900/40 dark:bg-green-950/20 px-4 py-3 text-sm text-green-800 dark:text-green-300 mb-4">
      <FileJson className="h-4 w-4 shrink-0" />
      <span>
        Form pre-filled from <strong>{fileName}</strong> — review and edit, then submit.
      </span>
      <button
        className="ml-auto text-green-600 hover:text-green-800 dark:text-green-400"
        onClick={onClear}
        title="Clear and start over"
        data-testid="button-clear-upload"
      >
        <X className="h-4 w-4" />
      </button>
    </div>
  );
}

function JsonUploadZone({
  onParsed,
}: {
  onParsed: (data: ParsedRequest, fileName: string) => void;
}) {
  const [dragging, setDragging] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [fieldErrors, setFieldErrors] = useState<string[]>([]);
  const fileInputRef = useRef<HTMLInputElement>(null);

  function readFile(file: File) {
    if (!file.name.endsWith(".json") && file.type !== "application/json") {
      setError("Please select a .json file generated by the CPR Training Request Form.");
      setFieldErrors([]);
      return;
    }
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const raw = JSON.parse(e.target?.result as string);
        const { data, blockingErrors } = parseImportedJson(raw);
        if (blockingErrors.length > 0) {
          setFieldErrors(blockingErrors);
          setError(null);
          return;
        }
        setError(null);
        setFieldErrors([]);
        onParsed(data, file.name);
      } catch (err) {
        setError(
          err instanceof SyntaxError
            ? "The file isn't valid JSON. Make sure you're uploading a CPR_Request_*.json file exported from the offline request form."
            : "Could not read the file. Make sure it's a JSON file exported from the offline request form."
        );
        setFieldErrors([]);
      }
    };
    reader.readAsText(file);
  }

  const handleDrop = useCallback((e: React.DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setDragging(false);
    const file = e.dataTransfer.files[0];
    if (file) readFile(file);
  }, []);

  const handleDragOver = useCallback((e: React.DragEvent<HTMLDivElement>) => {
    e.preventDefault();
    setDragging(true);
  }, []);

  const handleDragLeave = useCallback(() => {
    setDragging(false);
  }, []);

  function handleFileInput(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    if (file) readFile(file);
    e.target.value = "";
  }

  return (
    <div className="space-y-3 mb-6">
      <div
        className={[
          "flex flex-col items-center justify-center gap-3 rounded-xl border-2 border-dashed px-6 py-7 transition-colors cursor-pointer",
          dragging
            ? "border-primary bg-primary/5"
            : "border-border hover:border-primary/50 hover:bg-muted/40",
        ].join(" ")}
        onDrop={handleDrop}
        onDragOver={handleDragOver}
        onDragLeave={handleDragLeave}
        onClick={() => fileInputRef.current?.click()}
        data-testid="intake-upload-dropzone"
      >
        <div className="flex h-10 w-10 items-center justify-center rounded-full bg-muted">
          <Upload className="h-4 w-4 text-muted-foreground" />
        </div>
        <div className="text-center">
          <p className="text-sm font-medium text-foreground">
            Drop your request file here, or{" "}
            <span className="text-primary underline underline-offset-2">browse</span>
          </p>
          <p className="text-xs text-muted-foreground mt-1">
            Accepts{" "}
            <code className="text-xs bg-muted px-1 py-0.5 rounded">CPR_Request_*.json</code>{" "}
            files from the offline form
          </p>
        </div>
        <input
          ref={fileInputRef}
          type="file"
          accept=".json,application/json"
          className="hidden"
          onChange={handleFileInput}
          data-testid="intake-file-input"
        />
      </div>

      {error && (
        <div
          className="flex items-start gap-2 rounded-lg border border-destructive/30 bg-destructive/10 px-4 py-3 text-sm text-destructive"
          data-testid="intake-upload-error"
        >
          <AlertCircle className="h-4 w-4 mt-0.5 shrink-0" />
          <span>{error}</span>
        </div>
      )}

      {fieldErrors.length > 0 && (
        <div
          className="rounded-lg border border-destructive/30 bg-destructive/10 px-4 py-3 text-sm text-destructive space-y-1"
          data-testid="intake-upload-field-errors"
        >
          <div className="flex items-center gap-2 font-medium">
            <AlertCircle className="h-4 w-4 shrink-0" />
            <span>This file doesn't look like a CPR Training Request export:</span>
          </div>
          <ul className="list-disc list-inside pl-1 space-y-0.5">
            {fieldErrors.map((err, i) => (
              <li key={i}>{err}</li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

function IntakePage() {
  const [submitted, setSubmitted] = useState(false);
  const [showUpload, setShowUpload] = useState(false);
  const [uploadedValues, setUploadedValues] = useState<ParsedRequest | null>(null);
  const [uploadedFileName, setUploadedFileName] = useState<string | null>(null);
  // Key changes when uploadedValues changes, forcing TrainingRequestForm to remount with new initialValues
  const [formKey, setFormKey] = useState(0);

  function handleParsed(data: ParsedRequest, fileName: string) {
    setUploadedValues(data);
    setUploadedFileName(fileName);
    setShowUpload(false);
    setFormKey((k) => k + 1);
  }

  function handleClearUpload() {
    setUploadedValues(null);
    setUploadedFileName(null);
    setFormKey((k) => k + 1);
  }

  return (
    <div className="min-h-screen bg-background text-foreground flex flex-col">
      <header className="border-b border-border bg-card px-6 py-4 flex items-center gap-3">
        <div className="h-9 w-9 rounded-lg bg-primary text-primary-foreground flex items-center justify-center flex-shrink-0">
          <HeartPulse className="h-5 w-5" />
        </div>
        <div className="leading-tight">
          <div className="font-bold text-base tracking-tight">PulsePoint</div>
          <div className="text-[10px] text-muted-foreground uppercase tracking-wider">
            CPR Training Hub
          </div>
        </div>
      </header>

      <main className="flex-1 flex items-start justify-center px-4 py-10">
        <div className="w-full max-w-2xl">
          {submitted ? (
            <Card>
              <CardContent className="pt-10 pb-10 flex flex-col items-center text-center gap-4">
                <div className="h-16 w-16 rounded-full bg-emerald-500/10 flex items-center justify-center">
                  <CheckCircle2 className="h-8 w-8 text-emerald-600" />
                </div>
                <div>
                  <h2 className="text-xl font-bold mb-1">Request received!</h2>
                  <p className="text-muted-foreground text-sm max-w-sm mx-auto">
                    Your request has been received — we'll be in touch soon!
                    Check your inbox for a confirmation email, and we'll follow
                    up shortly to finalize the schedule.
                  </p>
                </div>
                <Button
                  variant="outline"
                  data-testid="button-check-status-link"
                  onClick={() => {
                    window.location.href = `${import.meta.env.BASE_URL}status`;
                  }}
                >
                  Check request status
                </Button>
              </CardContent>
            </Card>
          ) : (
            <>
              <div className="mb-6 flex items-start justify-between gap-4">
                <div>
                  <h1 className="text-2xl font-bold tracking-tight">
                    Request CPR training
                  </h1>
                  <p className="text-muted-foreground mt-1">
                    Tell us where you'd like CPR training and when works best.
                    We'll route this to our team.
                  </p>
                </div>
                {!showUpload && (
                  <Button
                    variant="outline"
                    size="sm"
                    className="shrink-0 mt-1"
                    onClick={() => setShowUpload(true)}
                    data-testid="button-show-upload"
                  >
                    <FileJson className="h-4 w-4 mr-1.5" />
                    Upload request file
                  </Button>
                )}
              </div>

              {showUpload && (
                <div>
                  <div className="flex items-center justify-between mb-3">
                    <p className="text-sm font-medium text-foreground">
                      Already have a request file? Upload it below to pre-fill the form.
                    </p>
                    <button
                      className="text-muted-foreground hover:text-foreground"
                      onClick={() => setShowUpload(false)}
                      title="Dismiss"
                      data-testid="button-dismiss-upload"
                    >
                      <X className="h-4 w-4" />
                    </button>
                  </div>
                  <JsonUploadZone onParsed={handleParsed} />
                </div>
              )}

              <Card>
                <CardContent className="pt-6">
                  {uploadedFileName && (
                    <UploadBanner
                      fileName={uploadedFileName}
                      onClear={handleClearUpload}
                    />
                  )}
                  <TrainingRequestForm
                    key={formKey}
                    initialValues={uploadedValues ?? undefined}
                    onSuccess={() => setSubmitted(true)}
                  />
                </CardContent>
              </Card>
            </>
          )}
        </div>
      </main>
    </div>
  );
}

export default function PublicIntake() {
  return <IntakePage />;
}
